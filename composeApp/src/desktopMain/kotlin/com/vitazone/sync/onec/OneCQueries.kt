package com.vitazone.sync.onec

import java.time.LocalDate

/**
 * Запросы к базе «Optom» — те же источники, что в отчётах:
 *  - «Продажа отчети» / Номенклатура-Куратор → РегистрНакопления.Остатки.Обороты
 *  - «Остатки2» / Вариант2 → РегистрНакопления.Склады.ОстаткиИОбороты
 */
object OneCQueries {

    fun all(from: LocalDate?, to: LocalDate, includeDaily: Boolean): List<OneCComClient.Query> {
        val start = OneCComClient.dateLiteral(from, endOfDay = false)
        val end = OneCComClient.dateLiteral(to, endOfDay = true)
        return listOfNotNull(
            OneCComClient.Query("dup", DUPLICATE_CODES),
            OneCComClient.Query("sales", SALES.replace("&НачалоПериода", start).replace("&КонецПериода", end)),
            OneCComClient.Query("stock", STOCK.replace("&НачалоПериода", start).replace("&КонецПериода", end)),
            if (includeDaily) OneCComClient.Query("daily", DAILY.replace("&НачалоПериода", start).replace("&КонецПериода", end)) else null,
        )
    }

    const val CHECK = """
ВЫБРАТЬ
	КОЛИЧЕСТВО(*) КАК Количество
ИЗ
	Справочник.Номенклатура КАК Н"""

    /** Повторяющиеся баркоды: один КОД у 2+ товаров (без помеченных на удаление) */
    const val DUPLICATE_CODES = """
ВЫБРАТЬ
	Н.Код КАК Код
ИЗ
	Справочник.Номенклатура КАК Н
ГДЕ
	НЕ Н.ПометкаУдаления
	И Н.Код <> ""
СГРУППИРОВАТЬ ПО
	Н.Код
ИМЕЮЩИЕ
	КОЛИЧЕСТВО(*) > 1"""

    /** Продажа отчети: обороты регистра «Остатки» по Номенклатура / Контрагенты / ДокНомер */
    const val SALES = """
ВЫБРАТЬ
	ЕСТЬNULL(В.Номенклатура.Код, "") КАК Код,
	ЕСТЬNULL(В.Номенклатура.Наименование, "") КАК Номенклатура,
	ЕСТЬNULL(В.Контрагенты.Наименование, "") КАК Контрагент,
	ЕСТЬNULL(В.Контрагенты.инн, 0) КАК ИНН,
	ЕСТЬNULL(В.ДокНомер.Наименование, "") КАК ДокНомер,
	В.ДокНомер.ДатаСоставления КАК Дата,
	ЕСТЬNULL(В.ДокНомер.МП.Код, "") КАК МП,
	В.Кол КАК Кол,
	В.Сумма КАК Сумма
ИЗ
	(ВЫБРАТЬ
		Т.Номенклатура КАК Номенклатура,
		Т.Контрагенты КАК Контрагенты,
		Т.ДокНомер КАК ДокНомер,
		СУММА(Т.КолвоРасход) КАК Кол,
		СУММА(Т.СуммаРасход) КАК Сумма
	ИЗ
		РегистрНакопления.Остатки.Обороты(&НачалоПериода, &КонецПериода, , ) КАК Т
	СГРУППИРОВАТЬ ПО
		Т.Номенклатура,
		Т.Контрагенты,
		Т.ДокНомер) КАК В"""

    /** Остатки2 / Вариант2 — Итого по товару. Сумма реализации = СуммаРасход + ПрибыльПриход */
    const val STOCK = """
ВЫБРАТЬ
	ЕСТЬNULL(В.Номенклатура.Код, "") КАК Код,
	ЕСТЬNULL(В.Номенклатура.Наименование, "") КАК Номенклатура,
	В.КолНач КАК КолНач,
	В.КолПриход КАК КолПриход,
	В.КолРасход КАК КолРасход,
	В.КолКон КАК КолКон,
	В.СуммаРеализации КАК СуммаРеализации,
	В.СуммаКон КАК СуммаКон
ИЗ
	(ВЫБРАТЬ
		Т.Номенклатура КАК Номенклатура,
		СУММА(Т.КолВоНачальныйОстаток) КАК КолНач,
		СУММА(Т.КолВоПриход) КАК КолПриход,
		СУММА(Т.КолВоРасход) КАК КолРасход,
		СУММА(Т.КолВоКонечныйОстаток) КАК КолКон,
		СУММА(Т.СуммаРасход + Т.ПрибыльПриход) КАК СуммаРеализации,
		СУММА(Т.СуммаКонечныйОстаток) КАК СуммаКон
	ИЗ
		РегистрНакопления.Склады.ОстаткиИОбороты(&НачалоПериода, &КонецПериода, , , ) КАК Т
	СГРУППИРОВАТЬ ПО
		Т.Номенклатура) КАК В"""

    /** Остатки2 / Вариант2 — по дням (только дни с движением, как в 1С) */
    const val DAILY = """
ВЫБРАТЬ
	В.Период КАК Дата,
	ЕСТЬNULL(В.Номенклатура.Код, "") КАК Код,
	ЕСТЬNULL(В.Номенклатура.Наименование, "") КАК Номенклатура,
	В.КолНач КАК КолНач,
	В.КолПриход КАК КолПриход,
	В.КолРасход КАК КолРасход,
	В.КолКон КАК КолКон,
	В.СуммаРеализации КАК СуммаРеализации,
	В.СуммаКон КАК СуммаКон
ИЗ
	(ВЫБРАТЬ
		Т.Период КАК Период,
		Т.Номенклатура КАК Номенклатура,
		СУММА(Т.КолВоНачальныйОстаток) КАК КолНач,
		СУММА(Т.КолВоПриход) КАК КолПриход,
		СУММА(Т.КолВоРасход) КАК КолРасход,
		СУММА(Т.КолВоКонечныйОстаток) КАК КолКон,
		СУММА(Т.СуммаРасход + Т.ПрибыльПриход) КАК СуммаРеализации,
		СУММА(Т.СуммаКонечныйОстаток) КАК СуммаКон
	ИЗ
		РегистрНакопления.Склады.ОстаткиИОбороты(&НачалоПериода, &КонецПериода, День, , ) КАК Т
	СГРУППИРОВАТЬ ПО
		Т.Период,
		Т.Номенклатура) КАК В"""
}
